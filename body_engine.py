"""
body_engine.py — 体型分析
根据身高、体重计算 BMI 与体型档位，结合体型（shape）给出显高/显瘦的版型与穿搭建议。
"""


def calc_bmi(height_cm, weight_kg):
    if not height_cm or not weight_kg or height_cm <= 0 or weight_kg <= 0:
        return None
    return round(weight_kg / ((height_cm / 100.0) ** 2), 1)


def bmi_category(bmi):
    """中国成人 BMI 标准。"""
    if bmi is None:
        return '正常'
    if bmi < 18.5:
        return '偏瘦'
    if bmi < 24.0:
        return '正常'
    if bmi < 28.0:
        return '偏胖'
    return '肥胖'


def height_category(height_cm):
    if height_cm < 158:
        return '娇小'
    if height_cm <= 172:
        return '中等'
    return '高挑'


