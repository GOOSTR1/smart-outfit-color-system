def body_summary(profile, lang):
    """返回一行简短的身材分析摘要。"""
    bmi = calc_bmi(profile.get('height', 165), profile.get('weight', 55))
    bcat = bmi_category(bmi)
    hcat = height_category(profile.get('height', 165))
    shape = profile.get('body_shape', 'H型')
    if lang == 'zh':
        return (f"BMI {bmi}（{BMI_NAME[bcat]['zh']}）· "
                f"身高{HEIGHT_NAME[hcat]['zh']} · {SHAPE_NAME[shape]['zh']}")
    return (f"BMI {bmi} ({BMI_NAME[bcat]['th']}) · "
            f"{HEIGHT_NAME[hcat]['th']} · {SHAPE_NAME[shape]['th']}")
